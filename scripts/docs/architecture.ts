const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function card(c: Card): string {
  const pill = Math.round(16 + c.cost.length * 7.6);
  return `  <g transform="translate(${c.x} ${c.y})">
    <rect width="${W}" height="${H}" rx="14" fill="#ffffff" stroke="#c9ccd2" filter="url(#mold)"/>
    <rect x="14" y="16" width="48" height="48" rx="10" fill="#e7e9ec"/>
    <g transform="translate(24 26) scale(1.1667)">${icons[c.icon]}</g>
    <text x="76" y="38" class="name">${esc(c.name)}</text>
    <text x="76" y="58" class="sub">${esc(c.sub)}</text>
    <g transform="translate(76 68)">
      <rect width="${pill}" height="20" rx="10" fill="#ff5f1f"/>
      <text x="8" y="14" class="cost">${esc(c.cost)}</text>
    </g>
  </g>`;
}

function arrow([d, dashed, label, lx, ly]: (typeof arrows)[number]): string {
  const line = dashed
    ? `<path d="${d}" fill="none" stroke="#7c818a" stroke-width="2.5" stroke-dasharray="7 6" marker-end="url(#head-mark)"/>`
    : `<path d="${d}" fill="none" stroke="#53575e" stroke-width="2" marker-end="url(#head-soft)"/>`;
  const text = label
    ? `\n  <text x="${lx}" y="${ly}" class="hud" font-size="10.5" fill="#7c818a">${esc(label)}</text>`
    : '';
  return `  ${line}${text}`;
}

